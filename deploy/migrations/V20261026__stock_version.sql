-- Independent stock baseline version.
--
-- product.stock_version only advances when a merchant explicitly resets stock.
-- order_item.stock_version stores the product baseline version that the successful
-- stock deduction belonged to. Cancelling an order restores stock only while both
-- versions still match, so a reset baseline is never increased by an old order.
--
-- Existing rows default to 0: before this migration there was no baseline tracking,
-- and every existing product starts at the same initial baseline. The first explicit
-- reset after deployment advances the product to 1 and prevents older orders from
-- restoring onto that new baseline.
--
-- Column-existence checks keep the migration safe when deploy/schema.sql already
-- created the columns for a fresh database. Do not edit this file after it has been
-- recorded in flyway_schema_history.

SET @takeout_product_stock_version_exists = (
    SELECT COUNT(*)
    FROM information_schema.columns
    WHERE table_schema = DATABASE()
      AND table_name = 'product'
      AND column_name = 'stock_version'
);
SET @takeout_product_stock_version_sql = IF(
    @takeout_product_stock_version_exists = 0,
    'ALTER TABLE `product` ADD COLUMN `stock_version` INT NOT NULL DEFAULT 0 COMMENT ''库存基准版本：商家显式重设库存时递增'' AFTER `stock`',
    'SELECT 1 AS product_stock_version_already_exists'
);
PREPARE takeout_product_stock_version_statement FROM @takeout_product_stock_version_sql;
EXECUTE takeout_product_stock_version_statement;
DEALLOCATE PREPARE takeout_product_stock_version_statement;

SET @takeout_order_item_stock_version_exists = (
    SELECT COUNT(*)
    FROM information_schema.columns
    WHERE table_schema = DATABASE()
      AND table_name = 'order_item'
      AND column_name = 'stock_version'
);
SET @takeout_order_item_stock_version_sql = IF(
    @takeout_order_item_stock_version_exists = 0,
    'ALTER TABLE `order_item` ADD COLUMN `stock_version` INT NOT NULL DEFAULT 0 COMMENT ''预扣库存时的商品库存基准版本'' AFTER `quantity`',
    'SELECT 1 AS order_item_stock_version_already_exists'
);
PREPARE takeout_order_item_stock_version_statement FROM @takeout_order_item_stock_version_sql;
EXECUTE takeout_order_item_stock_version_statement;
DEALLOCATE PREPARE takeout_order_item_stock_version_statement;
